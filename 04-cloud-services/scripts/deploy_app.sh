#!/usr/bin/env bash
# deploy_app.sh — run ON the EC2 instance (AlmaLinux 9) as root. Deploys the app from this repo.
#   1. copy app -> /opt/cloudops/app, python venv, pip install
#   2. build /etc/cloudops/app.env from SSM parameters (/cloudops/<env>/*) — the only place secrets live
#   3. install systemd unit + nginx reverse proxy config, SELinux booleans
#   4. start CloudWatch agent with ../aws/cloudwatch-agent-config.json
#   5. restart, health check
# Safe to re-run for every new version (git pull && sudo ./deploy_app.sh).
#
# Usage: sudo ./deploy_app.sh [--env dev] [--skip-cloudwatch] [--dry-run]
source "$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)/lib/common.sh"
parse_common_flags "$@"; set -- "${REMAINING[@]}"
SKIP_CW=false
while [[ $# -gt 0 ]]; do
  case "$1" in --skip-cloudwatch) SKIP_CW=true ;; *) die "unknown option $1" ;; esac; shift
done

MODULE_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
APP_SRC="$MODULE_DIR/app"
APP_DST="/opt/cloudops/app"
VENV="/opt/cloudops/venv"
ENV_FILE="/etc/cloudops/app.env"
PY="python3.11"

if [[ "$DRY_RUN" == false ]]; then
  [[ "$EUID" -eq 0 ]] || die "run with sudo (or --dry-run)"
  command -v dnf >/dev/null || die "this script targets AlmaLinux/RHEL 9"
  id cloudops &>/dev/null || die "user 'cloudops' missing — did user-data run? (see /var/log/user-data.log)"
fi
[[ "$DRY_RUN" == true ]] || need_cmd aws rsync curl

# Region from instance metadata (IMDSv2) so the aws cli works without config.
if [[ -z "${AWS_REGION:-}" && "$DRY_RUN" == false ]]; then
  TOKEN="$(curl -sX PUT http://169.254.169.254/latest/api/token -H 'X-aws-ec2-metadata-token-ttl-seconds: 60' || true)"
  AWS_REGION="$(curl -s -H "X-aws-ec2-metadata-token: $TOKEN" http://169.254.169.254/latest/meta-data/placement/region || true)"
  export AWS_REGION AWS_DEFAULT_REGION="$AWS_REGION"
fi

step "1. Application files + virtualenv"
run install -d -o cloudops -g cloudops -m 0755 /opt/cloudops
run rsync -a --delete --exclude '.env' --exclude '__pycache__' --exclude 'tests' "$APP_SRC/" "$APP_DST/"
run chown -R cloudops:cloudops "$APP_DST"
if [[ ! -x "$VENV/bin/python" ]]; then
  run "$PY" -m venv "$VENV"
fi
run "$VENV/bin/pip" install --quiet --upgrade pip
run "$VENV/bin/pip" install --quiet -r "$APP_SRC/requirements-aws.txt"

step "2. Environment file from SSM (/cloudops/$ENV_NAME/*)"
if [[ "$DRY_RUN" == true ]]; then
  log "+ aws ssm get-parameters-by-path --path /cloudops/$ENV_NAME --with-decryption > $ENV_FILE (0600 root)"
else
  install -d -m 0700 /etc/cloudops
  tmp="$(mktemp)"
  {
    echo "# generated by deploy_app.sh $(date -Is) from SSM /cloudops/$ENV_NAME — do not edit, do not copy"
    echo "APP_ENV=production"
    echo "LOG_FORMAT=json"
    echo "GIT_SHA=$(git -C "$MODULE_DIR" rev-parse --short HEAD 2>/dev/null || echo unknown)"
    aws ssm get-parameters-by-path --path "/cloudops/$ENV_NAME" --with-decryption --output text \
      --query 'Parameters[].[Name,Value]' | while IFS=$'\t' read -r name value; do
        printf '%s=%s\n' "${name##*/}" "$value"
      done
  } > "$tmp"
  grep -q '^DB_HOST=' "$tmp" || die "DB_HOST not in SSM — run rds_create.sh (or ssm_params.sh put DB_HOST ...)"
  grep -q '^DB_PASSWORD=' "$tmp" || die "DB_PASSWORD not in SSM"
  if ! grep -q '^SECRET_KEY=' "$tmp"; then
    # First deploy: generate a Flask secret and keep it in SSM so restarts don't change it.
    sk="$(openssl rand -hex 32)"
    aws ssm put-parameter --name "/cloudops/$ENV_NAME/SECRET_KEY" --type SecureString --value "$sk" --overwrite >/dev/null
    echo "SECRET_KEY=$sk" >> "$tmp"
  fi
  install -m 0600 -o root -g root "$tmp" "$ENV_FILE"; rm -f "$tmp"
  log "wrote $ENV_FILE ($(grep -c = "$ENV_FILE") keys, values hidden)"
fi
# systemd reads the file as root before dropping to the cloudops user, so the app user never
# gets file access to the secrets at rest.

step "3. systemd unit + nginx"
run install -m 0644 "$MODULE_DIR/aws/systemd/cloudops.service" /etc/systemd/system/cloudops.service
run install -m 0644 "$MODULE_DIR/aws/nginx/cloudops.conf" /etc/nginx/conf.d/cloudops.conf
run install -d -o cloudops -g cloudops -m 0755 /var/log/cloudops
if [[ "$DRY_RUN" == false ]]; then
  # Disable nginx's default server block so ours is the only :80 listener.
  sed -i 's/^\(\s*\)listen\s\+80;/\1listen 8080;/; s/^\(\s*\)listen\s\+\[::\]:80;/\1listen [::]:8080;/' /etc/nginx/nginx.conf
  if command -v setsebool >/dev/null && [[ "$(getenforce)" == "Enforcing" ]]; then
    setsebool -P httpd_can_network_connect 1      # let nginx proxy to 127.0.0.1:8000
    semanage fcontext -a -t httpd_sys_content_t "$APP_DST/cloudops/static(/.*)?" 2>/dev/null || true
    restorecon -R "$APP_DST/cloudops/static"
  fi
fi
run nginx -t
run systemctl daemon-reload
run systemctl enable --now nginx
run systemctl enable cloudops
run systemctl restart cloudops

step "4. CloudWatch agent"
if [[ "$SKIP_CW" == true ]]; then
  log "skipped (--skip-cloudwatch)"
elif [[ -x /opt/aws/amazon-cloudwatch-agent/bin/amazon-cloudwatch-agent-ctl || "$DRY_RUN" == true ]]; then
  run install -m 0644 "$MODULE_DIR/aws/cloudwatch-agent-config.json" /opt/aws/amazon-cloudwatch-agent/etc/cloudops.json
  run /opt/aws/amazon-cloudwatch-agent/bin/amazon-cloudwatch-agent-ctl -a fetch-config -m ec2 -s \
      -c file:/opt/aws/amazon-cloudwatch-agent/etc/cloudops.json
  # The agent runs as 'cwagent'; let it read our log file.
  run setfacl -m u:cwagent:rx /var/log/cloudops
  run chmod 0644 /var/log/cloudops/app.log
else
  warn "CloudWatch agent not installed (user-data failed?) — logs stay local in /var/log/cloudops/app.log"
fi

step "5. Health check"
if [[ "$DRY_RUN" == false ]]; then
  sleep 2
  if curl -fsS --max-time 5 http://127.0.0.1/health/ready; then
    echo; log "OK: app is up and the database is reachable"
    log "Open http://$(curl -s -H "X-aws-ec2-metadata-token: ${TOKEN:-}" http://169.254.169.254/latest/meta-data/public-ipv4 || hostname -I | awk '{print $1}')/"
  else
    echo; warn "readiness failed. Check: journalctl -u cloudops -n 50 ; tail /var/log/cloudops/app.log"
    exit 1
  fi
fi
